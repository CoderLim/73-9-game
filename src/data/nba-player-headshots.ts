function normalizePlayerName(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[.’'\-]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

const NORMALIZED_NBA_PLAYER_IDS = Object.fromEntries(
  Object.entries(NBA_PLAYER_IDS).map(([name, id]) => [
    normalizePlayerName(name),
    id,
  ])
) as Record<string, number>;

const PLAYER_NAME_ALIASES: Record<string, string> = {
  'gg jackson ii': 'gg jackson',
  'pj washington': 'pj washington',
  'robert williams': 'robert williams iii',
};

export function getNbaPlayerHeadshotUrl(name: string): string | null {
  const normalized = normalizePlayerName(name);
  const alias = PLAYER_NAME_ALIASES[normalized] ?? normalized;
  const playerId = NORMALIZED_NBA_PLAYER_IDS[alias];
  return playerId
    ? `https://cdn.nba.com/headshots/nba/latest/260x190/${playerId}.png`
    : null;
}
